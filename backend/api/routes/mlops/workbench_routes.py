@mlops_workbench_bp.route("/upload/<dataset_type>", methods=["POST"])
def mlops_upload_dataset(dataset_type):
    """
    POST /api/mlops/upload/<dataset_type>
    Upload a CSV or Parquet file and register it in the MLOps dataset registry.

    Special case: if dataset_type == 'custom', the actual type name must be
    supplied as a query param: ?custom_name=wire_transfers
    (or as a JSON body field 'custom_name')

    Returns:
      { success, data: { dataset_id, dataset_type, row_count, columns, column_types, file_path } }
    """
    try:
        # Resolve the effective dataset type
        raw_type = str(dataset_type or "").strip().lower()
        if raw_type == "custom":
            custom_name = (
                request.args.get("custom_name")
                or (request.form.get("custom_name") if request.form else None)
            )
            if not custom_name:
                return jsonify({
                    "success": False,
                    "error": "custom_name query parameter is required when dataset_type is 'custom'.",
                    "error_code": "MISSING_CUSTOM_NAME",
                }), 400
            raw_type = custom_name

        effective_type = _safe_dataset_type(raw_type)

        # Block pipeline artefact types
        if effective_type in PIPELINE_ARTEFACT_TYPES:
            return jsonify({
                "success": False,
                "error": (
                    f"'{effective_type}' is a pipeline artefact generated automatically by the workbench. "
                    "You cannot upload it directly. "
                    "Please upload only raw operational files: transactions, accounts, customers, alerts, cases, or str."
                ),
                "error_code": "ARTEFACT_TYPE_REJECTED",
            }), 400

        if "file" not in request.files:
            return jsonify({
                "success": False,
                "error": "No file part in request.",
                "error_code": "NO_FILE",
            }), 400

        file = request.files["file"]
        file_error = _validate_upload_file(file)
        if file_error:
            return jsonify({"success": False, **file_error}), 400

        tenant_id, env_id = _get_env_ids()
        env_root = _resolve_env_path(env_id, tenant_id)
        data_dir = resolve_mlops_data_dir(env_root, create_if_missing=True)
        mlops_svc = _get_mlops_service(env_root)

        pipeline_id_raw = request.args.get("pipeline_id") or (request.form.get("pipeline_id") if request.form else None)
        try:
            pipeline_id = int(pipeline_id_raw) if pipeline_id_raw not in (None, "", []) else None
        except Exception:
            pipeline_id = None
        if pipeline_id is not None and pipeline_id <= 0:
            pipeline_id = None

        pipeline_type = (
            request.args.get("pipeline_type")
            or (request.form.get("pipeline_type") if request.form else None)
            or None
        )
        if not pipeline_type and pipeline_id:
            try:
                pipeline_identity = mlops_svc.get_pipeline_identity(tenant_id, env_id, int(pipeline_id))
                pipeline_type = pipeline_identity.get("pipeline_type") or "fcc"
            except Exception:
                pipeline_type = None
        pipeline_type = pipeline_type or "fcc"

        ext = Path(file.filename).suffix.lower()
        scope_dir = data_dir / (f"pipeline_{int(pipeline_id)}" if pipeline_id else f"shared_{pipeline_type}")
        scope_dir.mkdir(parents=True, exist_ok=True)
        save_path = scope_dir / f"{effective_type}{ext}"
        file.save(str(save_path))

        # Cross-module ingestion is disabled. MLOps uploads stay in the MLOps workspace only.
        persist_requested = _as_bool(
            request.args.get("persist_to_main_db")
            or (request.form.get("persist_to_main_db") if request.form else None)
        )
        isolation_warning = None
        if persist_requested:
            isolation_warning = (
                "persist_to_main_db is disabled for MLOps uploads. "
                "The dataset was kept inside the isolated MLOps workspace."
            )

        dataset = mlops_svc.register_dataset(
            tenant_id=tenant_id,
            env_id=env_id,
            pipeline_type=pipeline_type,
            pipeline_id=int(pipeline_id) if pipeline_id else None,
            dataset_type=effective_type,
            filename=f"{effective_type}{ext}",
            file_path=save_path,
        )
        if pipeline_id:
            try:
                mlops_svc.attach_pipeline_asset(
                    tenant_id=tenant_id,
                    env_id=env_id,
                    pipeline_id=int(pipeline_id),
                    asset_kind="dataset",
                    asset_id=dataset["dataset_id"],
                    stage="data_upload",
                    relation="uploaded_source",
                    metadata={"dataset_type": dataset["dataset_type"]},
                    numeric=True,
                )
            except Exception:
                pass

        response_payload = {
            "success": True,
            "data": {
                "dataset_id": dataset["dataset_id"],
                "pipeline_id": dataset.get("pipeline_id"),
                "pipeline_type": dataset.get("pipeline_type", pipeline_type),
                "dataset_type": dataset["dataset_type"],
                "filename": dataset["filename"],
                "file_path": dataset["file_path"],
                "row_count": dataset["row_count"],
                "columns": dataset["columns"],
                "column_types": dataset["column_types"],
                "persisted_to_main_db": False,
            },
        }
        if isolation_warning:
            response_payload["warning"] = isolation_warning

        return jsonify(response_payload), 200

    except ValueError as ve:
        return jsonify({"success": False, "error": str(ve), "error_code": "VALIDATION_ERROR"}), 400
    except Exception as exc:
        return jsonify({"success": False, "error": str(exc), "error_code": "SERVER_ERROR"}), 500

