@mlops_workbench_bp.route("/datasets", methods=["GET"])
def mlops_list_datasets():
    """
    GET /api/mlops/datasets
    List all datasets registered for the current environment.

    Query params:
      - sync=1|true|force  -> rescan mlops/data/ and register discovered files
      - sync=force         -> rescan and recompute metadata for existing files too

    Default behavior is fast list-only (no heavy file scan), which keeps startup
    responsive while still preserving explicit sync when needed.
    """
    try:
        tenant_id, env_id = _get_env_ids()
        env_root = _resolve_env_path(env_id, tenant_id)
        mlops_svc = _get_mlops_service(env_root)

        sync_param = str(request.args.get("sync") or "").strip().lower()
        do_sync = sync_param in {"1", "true", "yes", "on", "force", "full"}
        force_sync = sync_param in {"force", "full"}
        synced = []

        if do_sync:
            data_dir = resolve_mlops_data_dir(env_root, create_if_missing=False)
            if data_dir.exists():
                synced = mlops_svc.sync_from_directory(
                    tenant_id=tenant_id,
                    env_id=env_id,
                    data_dir=data_dir,
                    force=force_sync,
                )

        datasets = mlops_svc.list_datasets(tenant_id, env_id)

        # â”€â”€ Split into raw uploads vs pipeline artefacts â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
        # The frontend Upload screen shows only raw_datasets.
        # Pipeline artefacts (master, preprocessed) are surfaced in the context panel.
        raw_datasets       = [d for d in datasets if d.get("dataset_type") not in PIPELINE_ARTEFACT_TYPES]
        artefact_datasets  = [d for d in datasets if d.get("dataset_type") in PIPELINE_ARTEFACT_TYPES]

        return jsonify({
            "success":    True,
            "data":       datasets,            # full list for backward-compat
            "raw":        raw_datasets,        # only user-uploaded tables
            "artefacts":  artefact_datasets,   # workbench-generated artefacts
            "sync_applied": bool(do_sync),
            "sync_mode": "force" if force_sync else ("incremental" if do_sync else "none"),
            "sync_count": int(len(synced)),
        }), 200

    except ValueError as ve:
        return jsonify({"success": False, "error": str(ve), "error_code": "VALIDATION_ERROR"}), 400
    except Exception as exc:
        return jsonify({"success": False, "error": str(exc), "error_code": "SERVER_ERROR"}), 500


# â”€â”€â”€ Dataset Detail â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

@mlops_workbench_bp.route("/datasets/<int:dataset_id>", methods=["GET"])
def mlops_get_dataset(dataset_id):
    """GET /api/mlops/datasets/<id>"""
    try:
        tenant_id, env_id = _get_env_ids()
        env_root  = _resolve_env_path(env_id, tenant_id)
        mlops_svc = _get_mlops_service(env_root)
        dataset   = mlops_svc.get_dataset(tenant_id, env_id, dataset_id)
        if not dataset:
            return jsonify({"success": False, "error": "Dataset not found.", "error_code": "NOT_FOUND"}), 404
        return jsonify({"success": True, "data": dataset}), 200
    except ValueError as ve:
        return jsonify({"success": False, "error": str(ve), "error_code": "VALIDATION_ERROR"}), 400
    except Exception as exc:
        return jsonify({"success": False, "error": str(exc), "error_code": "SERVER_ERROR"}), 500


