def _validate_upload_file(file) -> dict | None:
    """
    Returns None when valid, or a dict with {error, error_code} when invalid.
    """
    if not file or file.filename == "":
        return {"error": "No file provided or empty filename.", "error_code": "NO_FILE"}

    ext = file.filename.rsplit(".", 1)[-1].lower() if "." in file.filename else ""
    if ext not in ALLOWED_EXTENSIONS:
        return {
            "error": f"File type '.{ext}' is not supported. Please upload a CSV or Parquet file.",
            "error_code": "INVALID_EXTENSION",
        }

    # Check file size â€” seek to end to get byte length
    file.stream.seek(0, 2)
    size_bytes = file.stream.tell()
    file.stream.seek(0)

    if size_bytes == 0:
        return {"error": "The uploaded file is empty.", "error_code": "EMPTY_FILE"}

    if size_bytes > MAX_FILE_BYTES:
        mb = size_bytes / (1024 ** 2)
        return {
            "error": f"File is {mb:.0f} MB â€” the maximum allowed size is 500 MB.",
            "error_code": "FILE_TOO_LARGE",
        }

    return None


def _as_bool(raw) -> bool:
    return str(raw or "").strip().lower() in {"1", "true", "yes", "on"}


