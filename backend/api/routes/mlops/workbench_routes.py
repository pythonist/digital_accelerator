@mlops_workbench_bp.route("/datasets/<int:dataset_id>/delete", methods=["POST"])
def mlops_delete_dataset(dataset_id):
    """
    POST /api/mlops/datasets/<id>/delete
    Remove a dataset from the registry (file is kept on disk for audit).
    Useful when a bank wants to re-upload with corrected data.
    """
    try:
        tenant_id, env_id = _get_env_ids()
        env_root  = _resolve_env_path(env_id, tenant_id)
        mlops_svc = _get_mlops_service(env_root)
        mlops_svc.delete_dataset(tenant_id, env_id, dataset_id)
        return jsonify({"success": True, "message": "Dataset removed from registry."}), 200
    except ValueError as ve:
        return jsonify({"success": False, "error": str(ve), "error_code": "VALIDATION_ERROR"}), 400
